# 표본 크기가 50개 이하인 작은 데이터들의 정규성 검정을 위해 고안된 방법. 즉 해당 데이터셋이 정규분포를 따르냐 따르지 않냐를 알 수 있는 검정법.
# Shapiro-Wilk검정은 매우 민감하여 데이터의 분포가 타겟 분포와 조금만 달라도 p-value가 작게 나와 귀무가설이 기각될 수 있다.
# 결과는 0~1 사이값을 가진다. 귀무가설(데이터가 정규분포에 따른다.)이 참이면 결과값은 이론적으로 1이다.

import numpy as np
import scipy.stats as sp
data_x = np.array([4.62, 4.09, 6.2, 8.24, 0.77, 5.55, 3.11, 11.97, 2.16, 3.24, 10.91, 11.36, 0.87])
w, p_value = sp.shapiro(data_x)
print(f"W: {w}")
print(f"p-value: {p_value}")